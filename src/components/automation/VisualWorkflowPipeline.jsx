import React, { useRef, useEffect } from 'react';
import {
  CheckCircle2,
  Clock,
  AlertCircle,
  ShieldCheck,
  Database,
  Sliders,
  Layers,
  Box,
  Zap,
  Activity,
  FileText,
  Bot,
  ChevronRight,
  ArrowRight,
  Loader2,
  Sparkles,
  Info
} from 'lucide-react';

const STAGE_ICON_MAP = {
  Bot,
  ShieldCheck,
  Database,
  Sliders,
  Layers,
  Box,
  Zap,
  CheckCircle2,
  Activity,
  FileText
};

export default function VisualWorkflowPipeline({
  stages = [],
  isExecuting = false,
  jobStatus = 'Draft',
  elapsedSeconds = 0,
  onInspectStage = null
}) {
  const scrollRef = useRef(null);

  // Fallback 10 stages if not yet generated by backend
  const displayStages = stages.length > 0 ? stages : [
    { id: 'user_request', stage_number: 1, name: 'User Request', short_name: 'Request', category: 'Interpretation', engine: 'LangGraph Interpreter', status: 'pending', summary: 'Natural language chemical intent parsing', icon: 'Bot' },
    { id: 'input_validation', stage_number: 2, name: 'Input Validation', short_name: 'Validation', category: 'Cheminformatics', engine: 'RDKit Sanitizer', status: 'pending', summary: 'Valence check & SMILES verification', icon: 'ShieldCheck' },
    { id: 'data_prep', stage_number: 3, name: 'Chemistry Data Preparation', short_name: 'Data Prep', category: 'Retrieval', engine: 'PubChem & RCSB', status: 'pending', summary: 'Literature & crystallographic query', icon: 'Database' },
    { id: 'workflow_planning', stage_number: 4, name: 'AI Workflow Planning', short_name: 'Planning', category: 'Architecture', engine: 'LangGraph StateGraph', status: 'pending', summary: 'Dynamic DAG step sequence planning', icon: 'Sliders' },
    { id: 'tool_selection', stage_number: 5, name: 'Tool & Model Selection', short_name: 'Model Selection', category: 'Governance', engine: 'Scientific Registry', status: 'pending', summary: 'Adapter routing & safety checkpoint', icon: 'Layers' },
    { id: 'molecular_processing', stage_number: 6, name: 'Molecular Processing', short_name: 'Structure Prep', category: '3D Geometry', engine: 'PubChem 3D & RDKit', status: 'pending', summary: '3D Conformer & coordinate minimization', icon: 'Box' },
    { id: 'computation_simulation', stage_number: 7, name: 'Computation or Simulation', short_name: 'Simulation', category: 'Quantum / ADMET', engine: 'PySCF DFT / DeepChem', status: 'pending', summary: 'Ab-initio DFT & Lipinski Ro5 calculation', icon: 'Zap' },
    { id: 'scientific_validation', stage_number: 8, name: 'Scientific Validation', short_name: 'Audit', category: 'Quality Sanity', engine: 'Verification Evaluator', status: 'pending', summary: 'Lipinski Ro5 & structural sanity audit', icon: 'CheckCircle2' },
    { id: 'results_generation', stage_number: 9, name: 'Results Generation', short_name: 'Synthesis', category: 'Aggregation', engine: 'Observable Aggregator', status: 'pending', summary: 'Matrix compilation of observables', icon: 'Activity' },
    { id: 'final_report', stage_number: 10, name: 'Final Report', short_name: 'Report', category: 'Documentation', engine: 'Report Compiler', status: 'pending', summary: 'Synthesis of peer-style report', icon: 'FileText' }
  ];

  // Calculate honest progress metrics
  const completedCount = displayStages.filter((s) => s.status === 'completed').length;
  const activeStage = displayStages.find((s) => s.status === 'running') ||
                      displayStages.find((s) => s.status === 'awaiting_approval') ||
                      (isExecuting ? displayStages[completedCount] : null);
  const activeStageIndex = activeStage ? displayStages.findIndex((s) => s.id === activeStage.id) : -1;
  const progressPercent = Math.round((completedCount / displayStages.length) * 100);

  // Auto-scroll active stage into view if horizontal overflow
  useEffect(() => {
    if (activeStageIndex >= 0 && scrollRef.current) {
      const stageElem = scrollRef.current.children[activeStageIndex];
      if (stageElem) {
        stageElem.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
      }
    }
  }, [activeStageIndex]);

  const formatTimer = (totalSec) => {
    const mins = Math.floor(totalSec / 60);
    const secs = (totalSec % 60).toFixed(1);
    return `${String(mins).padStart(2, '0')}:${String(secs).padStart(4, '0')}`;
  };

  return (
    <div className="w-full rounded-2xl border border-[var(--border-subtle)] bg-[var(--bg-card)] p-4 md:p-5 space-y-4 shadow-sm relative overflow-hidden">
      {/* Decorative ambient background accent */}
      <div className="absolute top-0 right-0 w-96 h-32 bg-orange-500/5 rounded-full blur-3xl pointer-events-none" />

      {/* Header telemetry bar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-[var(--border-subtle)] pb-3.5 relative z-10">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="text-xs md:text-sm font-bold text-[var(--text-primary)] flex items-center gap-2">
              <span>Visual AI Workflow Engine</span>
              <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-orange-500/10 text-orange-400 border border-orange-500/25 font-semibold">
                10-Stage Pipeline
              </span>
            </h3>
          </div>
          <p className="text-[11px] text-[var(--text-secondary)] mt-0.5">
            Deterministic state graph routing from initial prompt validation to final scientific synthesis.
          </p>
        </div>

        {/* Real telemetry counters */}
        <div className="flex items-center gap-2.5 font-mono text-xs">
          <div className="px-2.5 py-1 rounded-lg bg-[var(--bg-inner)] border border-[var(--border-subtle)] flex items-center gap-1.5 text-[var(--text-secondary)]">
            <Clock className="w-3.5 h-3.5 text-orange-400" />
            <span className="text-[10px] text-[var(--text-muted)]">ELAPSED:</span>
            <span className="font-bold text-[var(--text-primary)]">{formatTimer(elapsedSeconds)}</span>
          </div>

          <div className="px-2.5 py-1 rounded-lg bg-[var(--bg-inner)] border border-[var(--border-subtle)] flex items-center gap-1.5 text-[var(--text-secondary)]">
            <Activity className="w-3.5 h-3.5 text-emerald-400" />
            <span className="text-[10px] text-[var(--text-muted)]">PROGRESS:</span>
            <span className="font-bold text-emerald-400">{completedCount} / 10 ({progressPercent}%)</span>
          </div>
        </div>
      </div>

      {/* Honest Progress Bar */}
      <div className="w-full h-1.5 bg-[var(--bg-inner)] rounded-full overflow-hidden border border-[var(--border-subtle)] relative">
        <div
          className={`h-full transition-all duration-500 rounded-full ${
            jobStatus === 'Failed' ? 'bg-rose-500' :
            jobStatus === 'Completed' ? 'bg-emerald-500' :
            'bg-gradient-to-r from-orange-500 to-amber-400'
          }`}
          style={{ width: `${progressPercent}%` }}
        />
        {isExecuting && (
          <div className="absolute inset-0 bg-white/20 animate-pulse" />
        )}
      </div>

      {/* ─────────────────────────────────────────────────────────────────────
          CONNECTED STAGES NODE FLOW
         ───────────────────────────────────────────────────────────────────── */}
      <div
        ref={scrollRef}
        className="flex items-center gap-2.5 overflow-x-auto pb-2 pt-1 no-scrollbar select-none"
      >
        {displayStages.map((stage, idx) => {
          const isDone = stage.status === 'completed';
          const isRunning = stage.status === 'running' || (isExecuting && idx === activeStageIndex);
          const isAwaiting = stage.status === 'awaiting_approval';
          const isFailed = stage.status === 'failed';
          const isPending = stage.status === 'pending';

          const IconComp = STAGE_ICON_MAP[stage.icon] || Bot;
          const isLast = idx === displayStages.length - 1;

          return (
            <React.Fragment key={stage.id}>
              {/* Stage Node Card */}
              <div
                onClick={() => onInspectStage && onInspectStage(stage)}
                title={`Click to inspect Stage ${stage.stage_number}: ${stage.name}`}
                className={`relative shrink-0 w-44 md:w-48 p-3 rounded-xl border transition-all cursor-pointer group hover:scale-[1.02] active:scale-[0.98] ${
                  isRunning
                    ? 'border-orange-500/60 bg-gradient-to-b from-orange-500/15 via-[var(--bg-card)] to-[var(--bg-card)] shadow-lg ring-2 ring-orange-500/20'
                    : isDone
                    ? 'border-emerald-500/35 bg-emerald-500/5 hover:border-emerald-500/60 hover:bg-emerald-500/10'
                    : isAwaiting
                    ? 'border-amber-500/50 bg-amber-500/10 hover:border-amber-500 animate-pulse'
                    : isFailed
                    ? 'border-rose-500/40 bg-rose-500/5 hover:border-rose-500'
                    : 'border-[var(--border-subtle)] bg-[var(--bg-card)] opacity-65 hover:opacity-100 hover:border-slate-600'
                }`}
              >
                {/* Active Glowing Pulse Dot */}
                {isRunning && (
                  <span className="absolute -top-1 -right-1 flex h-3 w-3">
                    <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-orange-400 opacity-75" />
                    <span className="relative inline-flex rounded-full h-3 w-3 bg-orange-500" />
                  </span>
                )}

                {/* Top Badge: Number + Status */}
                <div className="flex items-center justify-between mb-2">
                  <div className="flex items-center gap-1.5">
                    <span className={`w-5 h-5 rounded-full flex items-center justify-center font-mono text-[10px] font-bold border ${
                      isDone ? 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30' :
                      isRunning ? 'bg-orange-500/20 text-orange-400 border-orange-500/40' :
                      isAwaiting ? 'bg-amber-500/20 text-amber-400 border-amber-500/40' :
                      isFailed ? 'bg-rose-500/20 text-rose-400 border-rose-500/40' :
                      'bg-slate-800 text-slate-400 border-slate-700'
                    }`}>
                      {stage.stage_number}
                    </span>
                    <span className="text-[9px] font-mono uppercase text-[var(--text-muted)] font-semibold truncate max-w-[80px]">
                      {stage.category}
                    </span>
                  </div>

                  {/* Status Indicator */}
                  {isDone ? (
                    <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400 shrink-0" />
                  ) : isRunning ? (
                    <Loader2 className="w-3.5 h-3.5 text-orange-400 animate-spin shrink-0" />
                  ) : isAwaiting ? (
                    <AlertCircle className="w-3.5 h-3.5 text-amber-400 shrink-0" />
                  ) : isFailed ? (
                    <AlertCircle className="w-3.5 h-3.5 text-rose-400 shrink-0" />
                  ) : (
                    <span className="w-2 h-2 rounded-full bg-slate-700 shrink-0" />
                  )}
                </div>

                {/* Stage Title */}
                <div className="space-y-1">
                  <div className="flex items-center gap-1.5">
                    <IconComp className={`w-3.5 h-3.5 shrink-0 ${
                      isDone ? 'text-emerald-400' :
                      isRunning ? 'text-orange-400' :
                      isAwaiting ? 'text-amber-400' :
                      isFailed ? 'text-rose-400' :
                      'text-[var(--text-muted)]'
                    }`} />
                    <span className="text-xs font-bold text-[var(--text-primary)] truncate block">
                      {stage.name}
                    </span>
                  </div>

                  {/* Engine Tag */}
                  <div className="text-[10px] font-mono text-[var(--text-muted)] truncate">
                    {stage.engine}
                  </div>

                  {/* Short Summary */}
                  <p className="text-[10.5px] text-[var(--text-secondary)] line-clamp-2 leading-snug pt-0.5">
                    {stage.summary}
                  </p>
                </div>

                {/* Inspect Action Cue */}
                <div className="mt-2.5 pt-2 border-t border-[var(--border-subtle)] flex items-center justify-between text-[9.5px] font-mono text-[var(--text-muted)] group-hover:text-orange-400 transition">
                  <span>Inspect details</span>
                  <ChevronRight className="w-3 h-3 group-hover:translate-x-0.5 transition" />
                </div>
              </div>

              {/* Connecting Flow Arrow / Directional Particles */}
              {!isLast && (
                <div className="shrink-0 flex items-center justify-center px-0.5 relative">
                  <div className={`w-5 h-0.5 relative rounded-full transition-colors ${
                    isDone
                      ? 'bg-emerald-500/60'
                      : isRunning
                      ? 'bg-gradient-to-r from-orange-500 to-amber-500/50'
                      : 'bg-slate-800'
                  }`}>
                    {/* Animated Directional Flow Particle */}
                    {(isRunning || (isDone && idx === activeStageIndex - 1)) && (
                      <span className="absolute -top-[3px] left-0 w-2 h-2 rounded-full bg-orange-400 shadow-[0_0_8px_#f97316] animate-arrowPulse" />
                    )}
                  </div>
                  <ArrowRight className={`w-3 h-3 ml-0.5 transition-colors ${
                    isDone ? 'text-emerald-400' :
                    isRunning ? 'text-orange-400' :
                    'text-slate-700'
                  }`} />
                </div>
              )}
            </React.Fragment>
          );
        })}
      </div>
    </div>
  );
}
